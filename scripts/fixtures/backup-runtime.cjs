const { app, BrowserWindow, session, safeStorage } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const argument = name => process.argv.find(value => value.startsWith(`--${name}=`))?.slice(name.length + 3)
const base = argument('root'), layout = argument('layout'), program = argument('program')
const mode = argument('mode'), sourceLayout = argument('source-layout'), archive = argument('archive'), origin = argument('origin')
const roaming = path.join(base, 'roaming')
const root = layout === 'portable' ? path.join(program, 'data') : path.join(roaming, 'sidekickai-opensource')
fs.mkdirSync(root, { recursive: true })
const realPath = app.getPath.bind(app)
app.getPath = name => name === 'exe' ? path.join(program, 'SidekickAI.exe') : name === 'appData' ? roaming : realPath(name)
Object.defineProperty(app, 'isPackaged', { value: true })
app.relaunch = () => {}
process.on('uncaughtException', error => { console.error(error); app.exit(1) })
const startup = require('./startup.cjs')
assert.equal(app.getPath('userData'), root)
assert.equal(app.getPath('sessionData'), root)
const backup = require('./backup.cjs')
const settings = backup.createSqliteJsonStore({ tableName: 'runtime_fixture', defaults: { value: '', secret: '', layout: '' } })
const draftKey = 'windowDraft:runtime:fixture'
const draft = { value: 'isolated source draft' }
app.whenReady().then(async () => {
  if (mode === 'import') {
    settings.set('value', 'before import')
    const imported = await backup.importAllDataDecrypted(archive, 'isolated-password', undefined, { mode: 'full' })
    assert.equal(imported.success, true, imported.error)
    assert.equal(settings.get('value'), 'before import')
  } else {
    if (mode === 'restore') {
      assert.equal(startup.startupRestore.restored, true, JSON.stringify(startup.startupRestore))
      const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'))
      assert.deepEqual(backup.restoreBackupDrafts(root, manifest.sensitiveDrafts), { restored: 1, unavailable: 0 })
      await backup.restoreBackupCookies(root, manifest.cookieSnapshots)
      backup.finishPendingRestore(root)
    }
    const target = session.fromPartition('persist:drill-browser')
    const window = new BrowserWindow({ show: false, webPreferences: { partition: 'persist:drill-browser', backgroundThrottling: false } })
    await window.loadURL(origin)
    if (mode === 'export') {
      settings.set('value', 'snapshot settings'); settings.set('layout', layout)
      settings.set('secret', backup.encryptString('snapshot credential'))
      backup.getAppSettingsTable().set(draftKey, safeStorage.encryptString(JSON.stringify(draft)).toString('base64'))
      await target.cookies.set({ url: origin, name: 'login', value: 'snapshot login', httpOnly: true, expirationDate: Date.now() / 1000 + 3600 })
      await session.defaultSession.cookies.set({ url: origin, name: 'default-login', value: 'default snapshot', expirationDate: Date.now() / 1000 + 3600 })
      await window.webContents.executeJavaScript('localStorage.setItem("fixture", "snapshot storage")')
      await window.webContents.executeJavaScript(`new Promise((resolve,reject)=>{const request=indexedDB.open('fixture',1);request.onupgradeneeded=()=>request.result.createObjectStore('values');request.onerror=()=>reject(request.error.message);request.onsuccess=()=>{const db=request.result;const tx=db.transaction('values','readwrite');tx.objectStore('values').put('snapshot indexed','draft');tx.oncomplete=()=>{db.close();resolve()};tx.onerror=()=>reject(tx.error.message)}})`)
      const exported = await backup.exportAllData(archive, { basicData: true, cookies: true, indexedDB: true, cache: true }, { password: 'isolated-password' })
      assert.equal(exported.success, true, exported.error)
      settings.set('value', 'later settings')
      await target.cookies.set({ url: origin, name: 'login', value: 'later login', httpOnly: true, expirationDate: Date.now() / 1000 + 3600 })
      fs.writeFileSync(path.join(root, 'retained-current.txt'), 'current-only data')
      const imported = await backup.importAllDataDecrypted(archive, 'isolated-password', undefined, { mode: 'full' })
      assert.equal(imported.success, true, imported.error)
      assert.equal(settings.get('value'), 'later settings')
      assert.equal((await target.cookies.get({ name: 'login' }))[0].value, 'later login')
    } else {
      assert.equal(settings.get('layout'), sourceLayout)
      assert.equal(settings.get('value'), 'snapshot settings')
      assert.equal(backup.decryptString(settings.get('secret')), 'snapshot credential')
      assert.deepEqual(JSON.parse(safeStorage.decryptString(Buffer.from(backup.getAppSettingsTable().get(draftKey), 'base64'))), draft)
      assert.equal(fs.readFileSync(path.join(root, 'retained-current.txt'), 'utf8'), 'current-only data')
      assert.equal((await target.cookies.get({ name: 'login' }))[0].value, 'snapshot login')
      assert.equal((await session.defaultSession.cookies.get({ name: 'default-login' }))[0].value, 'default snapshot')
      assert.equal(await window.webContents.executeJavaScript('localStorage.getItem("fixture")'), 'snapshot storage')
      assert.equal(await window.webContents.executeJavaScript(`new Promise((resolve,reject)=>{const request=indexedDB.open('fixture',1);request.onerror=()=>reject(request.error.message);request.onsuccess=()=>{const db=request.result;const query=db.transaction('values').objectStore('values').get('draft');query.onsuccess=()=>{db.close();resolve(query.result)};query.onerror=()=>reject(query.error.message)}})`), 'snapshot indexed')
    }
    window.destroy()
  }
  backup.closeModuleStateDb()
  fs.writeFileSync(path.join(base, `${mode}.ok`), 'ok')
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
